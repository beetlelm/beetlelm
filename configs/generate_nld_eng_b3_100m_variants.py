#!/usr/bin/env python3
"""
Generate 100M FineWeb B3 nld-eng variant YAMLs from the safe baseline.

Each variant flips exactly one differential feature on (matching the
2B variant settings in configs/b3_condition_sweep_2b/nld_L1-eng_L2/cl/),
keeping all other axes identical to train_nld_L1-eng_L2.safe.yaml.

Output dir: configs/humanscale_fineweb_bilingual/core/B3/variants_nld_eng_100m/
"""
from __future__ import annotations

import copy
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
BASE_YAML = (
    REPO / "configs" / "humanscale_fineweb_bilingual" / "core" / "B3"
    / "train_nld_L1-eng_L2.safe.yaml"
)
OUT_DIR = (
    REPO / "configs" / "humanscale_fineweb_bilingual" / "core" / "B3"
    / "variants_nld_eng_100m"
)

VARIANTS: dict[str, dict] = {
    # Continual-learning: Elastic Weight Consolidation at L1->L2 phase boundary.
    "ewc": {
        "ewc": {
            "enabled": True,
            "lambda_": 20.0,
            "n_fisher_samples": 10,
            "mu": 0.0,
            "trigger": "phase_change",
        },
    },
    # Continual-learning: LAMOL-style generative replay.
    # NOTE: prompt_style='unconditional' (was 'lang_tag' in 2B variant);
    # 'lang_tag' requires a tokenizer-specific lang_token_id wire-through that
    # the bilingual nl-en BPE tokenizer doesn't expose. Falling back to
    # unconditional gen-replay matches the v1 LAMOL paper.
    "lamol": {
        "generative_replay": {
            "enabled": True,
            "lambda_replay": 0.3,
            "replay_ratio": 0.3,
            "temperature": 0.9,
            "top_p": 0.92,
            "max_gen_len": 128,
            "prompt_style": "unconditional",
            "buffer_size": 1000,
            "trigger": "phase_change",
        },
    },
    # Meta-learning: hybrid MAML on minibatch slices.
    "maml": {
        "maml": {
            "enabled": True,
            "hybrid_ratio": 0.5,
            "n_way": 5,
            "k_shot": 1,
            "inner_steps": 3,
            "inner_lr": 0.1,
            "head": {
                "num_layers": 2,
                "hidden_dim": 256,
                "init_method": "xavier",
            },
        },
    },
    # Pre-pretraining: 500-step Shuffle-Dyck warmup before NL training begins.
    "pre-pretrain": {
        "pre_pretraining": {
            "enabled": True,
            "formal_lang": "shuffle_dyck",
            "steps": 500,
            "num_symbols": 20,
            "max_depth": 8,
            "p_open": 0.5,
            "vocab_offset": 0,
            "reset_optimizer": True,
            "save_stage1_checkpoint": True,
        },
    },
    # Working-memory ALiBi: linearly anneal slope from 2.0 -> 10.0 (CPLM
    # developmental curriculum). The 2B variant used 1.0 -> 0.0 which the
    # trainer rejects as "inverted" — per-head slope blows up at end of
    # training, shrinking the working-memory window (opposite of intent).
    "alibi": {
        "working_memory": {
            "enabled": True,
            "schedule": "linear",
            "initial_slope": 2.0,
            "final_slope": 10.0,
            "num_phases": 10,
            "decay_rate": 0.6,
        },
    },
    # Architecture growth: stack 2 identity-init layers at the phase boundary.
    "layer-growth": {
        "layer_growth": {
            "enabled": True,
            "strategy": "stack",
            "add_n_layers": 2,
            "init_mode": "identity",
            "freeze_old_layers": False,
            "trigger": "phase_change",
        },
    },
}


def _slug(variant: str) -> str:
    """Variant-name slug used in run_name (matches 2B convention)."""
    return variant.replace("_", "-")


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    with BASE_YAML.open() as f:
        base_cfg = yaml.safe_load(f)

    base_run = base_cfg["run_name"]  # ...-100m-nld-eng-safe
    # Drop the trailing "-safe" so per-variant suffix reads clean.
    if base_run.endswith("-safe"):
        base_run = base_run[: -len("-safe")]

    written = []
    for name, overlay in VARIANTS.items():
        cfg = copy.deepcopy(base_cfg)
        cfg["run_name"] = f"{base_run}-{_slug(name)}"
        # NOTE: token lacks create-repo perms on Beetle-FineWeb-100M-Variants org;
        # all variant pushes go to Beetle-FineWeb-100M alongside the baseline,
        # disambiguated by run_name suffix (-ewc, -lamol, etc.).
        cfg["hf_user"] = "Beetle-FineWeb-100M"
        for key, block in overlay.items():
            cfg[key] = block

        out = OUT_DIR / f"train_nld_L1-eng_L2.{_slug(name)}.yaml"
        with out.open("w") as f:
            f.write(
                "# AUTOGENERATED by configs/generate_nld_eng_b3_100m_variants.py\n"
                f"# Variant: {name} (single feature toggled vs B3 100M baseline)\n"
            )
            yaml.safe_dump(cfg, f, sort_keys=False, default_flow_style=False)
        written.append(out.relative_to(REPO))

    print(f"Wrote {len(written)} variant configs to {OUT_DIR.relative_to(REPO)}/:")
    for p in written:
        print(f"  {p}")


if __name__ == "__main__":
    main()
